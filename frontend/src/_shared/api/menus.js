import api from './axios';

/** Menus: ingredients (families of stock items), dishes, the Menus settings. Recipes are in stockOps.js. */
export const menusAPI = {
  ingredients: async (params) => (await api.get('/admin/menus/ingredients', { params })).data,
  saveIngredient: async (payload, id) => (id ? (await api.put(`/admin/menus/ingredients/${id}`, payload)) : (await api.post('/admin/menus/ingredients', payload))).data,
  removeIngredient: async (id) => (await api.delete(`/admin/menus/ingredients/${id}`)).data,
  suggestUnits: async (variantId, unitId) => (await api.post('/admin/menus/ingredients/suggest', { variant_id: variantId, unit_id: unitId })).data,
  dishes: async (params) => (await api.get('/admin/menus/dishes', { params })).data,
  saveDish: async (payload, id) => (id ? (await api.put(`/admin/menus/dishes/${id}`, payload)) : (await api.post('/admin/menus/dishes', payload))).data,
  soldOut: async (id, soldOut) => (await api.post(`/admin/menus/dishes/${id}/sold-out`, { sold_out: soldOut })).data,
  removeDish: async (id) => (await api.delete(`/admin/menus/dishes/${id}`)).data,
  menus: async () => (await api.get('/admin/menus/menus')).data,
  saveMenu: async (payload, id) => (id ? (await api.put(`/admin/menus/menus/${id}`, payload)) : (await api.post('/admin/menus/menus', payload))).data,
  removeMenu: async (id) => (await api.delete(`/admin/menus/menus/${id}`)).data,
  dishOptions: async (dishId) => (await api.get(`/admin/menus/dishes/${dishId}/options`)).data,
  saveDishOptions: async (dishId, groups) => (await api.put(`/admin/menus/dishes/${dishId}/options`, { groups })).data,
  orders: async (params) => (await api.get('/admin/menus/orders', { params })).data,
  setOrderStatus: async (id, to, reason) => (await api.post(`/admin/menus/orders/${id}/status`, { to, reason })).data,
  payOrder: async (id, tenders) => (await api.post(`/admin/menus/orders/${id}/pay`, { tenders })).data,
  channels: async () => (await api.get('/admin/menus/channels')).data,
  saveChannel: async (id, payload) => (await api.put(`/admin/menus/channels/${id}`, payload)).data,
  till: async (params) => (await api.get('/admin/menus/till', { params })).data,
  tillQuote: async (payload) => (await api.post('/admin/menus/till/quote', payload)).data,
  sell: async (payload) => (await api.post('/admin/menus/till/sell', payload)).data,
  openTab: async (payload) => (await api.post('/admin/menus/till/tabs', payload)).data,
  quoteTab: async (id, payload) => (await api.post(`/admin/menus/till/tabs/${id}/quote`, payload)).data,
  addToTab: async (id, payload) => (await api.post(`/admin/menus/till/tabs/${id}/add`, payload)).data,
  voidLine: async (id, line) => (await api.delete(`/admin/menus/till/tabs/${id}/lines/${line}`)).data,
  settleTab: async (id, payload) => (await api.post(`/admin/menus/till/tabs/${id}/settle`, payload)).data,
  cancelTab: async (id, reason) => (await api.post(`/admin/menus/till/tabs/${id}/cancel`, { reason })).data,
  receipt: async (id, width = 32) => (await api.get(`/admin/menus/orders/${id}/receipt`, { params: { width } })).data,
  floor: async (params) => (await api.get('/admin/menus/floor', { params })).data,
  saveArea: async (payload, id) => (id ? (await api.put(`/admin/menus/floor/areas/${id}`, payload)) : (await api.post('/admin/menus/floor/areas', payload))).data,
  removeArea: async (id) => (await api.delete(`/admin/menus/floor/areas/${id}`)).data,
  saveTable: async (payload, id) => (id ? (await api.put(`/admin/menus/floor/tables/${id}`, payload)) : (await api.post('/admin/menus/floor/tables', payload))).data,
  removeTable: async (id) => (await api.delete(`/admin/menus/floor/tables/${id}`)).data,
  saveLayout: async (places) => (await api.put('/admin/menus/floor/layout', { places })).data,
  tableAct: async (id, action, payload) => (await api.post(`/admin/menus/floor/tables/${id}/${action}`, payload ?? {})).data,
  tableQr: async (id) => (await api.get(`/admin/menus/floor/tables/${id}/qr`, { responseType: 'text', transformResponse: (r) => r })).data,
  moveTab: async (id, tableId) => (await api.post(`/admin/menus/till/tabs/${id}/move`, { table_id: tableId })).data,
  splitTab: async (id, lineIds) => (await api.post(`/admin/menus/till/tabs/${id}/split`, { line_ids: lineIds })).data,
  stations: async () => (await api.get('/admin/menus/kitchen/stations')).data,
  saveStation: async (payload, id) => (id ? (await api.put(`/admin/menus/kitchen/stations/${id}`, payload)) : (await api.post('/admin/menus/kitchen/stations', payload))).data,
  removeStation: async (id) => (await api.delete(`/admin/menus/kitchen/stations/${id}`)).data,
  screen: async (stationId) => (await api.get(`/admin/menus/kitchen/screen/${stationId}`)).data,
  expo: async () => (await api.get('/admin/menus/kitchen/expo')).data,
  ticket: async (id, action) => (await api.post(`/admin/menus/kitchen/tickets/${id}/${action}`)).data,
  settings: async () => (await api.get('/admin/menus/settings')).data,
  saveSettings: async (payload) => (await api.put('/admin/menus/settings', payload)).data,
};

export default menusAPI;
